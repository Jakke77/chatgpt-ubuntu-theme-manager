#!/usr/bin/python3
"""A real GTK application to visually exercise applied Hiili colors and icons."""
from pathlib import Path
import os
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import engine
variant = os.environ.get("THEME_PREVIEW_VARIANT", "hiili")
engine.apply(variant=variant)
import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Adw, Gio, Gtk, Gdk


class App(Adw.Application):
    def __init__(self):
        super().__init__(application_id="fi.hiili.Showcase")

    def do_activate(self):
        Adw.StyleManager.get_default().set_color_scheme(Adw.ColorScheme.FORCE_DARK)
        # Xvfb has no GNOME XSettings daemon: relay the applied desktop preference.
        Gtk.Settings.get_default().props.gtk_icon_theme_name = engine.settings("org.gnome.desktop.interface").get_string("icon-theme")
        icons = Gtk.IconTheme.get_for_display(Gdk.Display.get_default())
        folder = icons.lookup_icon("folder", None, 64, 1, Gtk.TextDirection.NONE, Gtk.IconLookupFlags.FORCE_REGULAR)
        assert "/icons/" + engine.palette(variant)["theme"] + "/" in folder.get_file().get_path(), folder.get_file().get_path()
        window = Adw.ApplicationWindow(application=self, title="Hiili — teeman esikatselu", default_width=740, default_height=760)
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)
        window.set_content(box)
        header = Adw.HeaderBar()
        header.set_title_widget(Adw.WindowTitle(title="Kotihakemisto", subtitle="Hiili · GTK 4 ja kuvakkeet"))
        back = Gtk.Button.new_from_icon_name("go-previous-symbolic")
        back.add_css_class("flat")
        header.pack_start(back)
        header.pack_start(Gtk.Button.new_from_icon_name("system-search-symbolic"))
        menu = Gtk.MenuButton(icon_name="open-menu-symbolic")
        popover = Gtk.Popover()
        menu.set_popover(popover)
        menu_box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=8, margin_start=14, margin_end=14, margin_top=14, margin_bottom=14)
        menu_box.append(Gtk.Label(label="Näkymän asetukset"))
        menu_box.append(Gtk.CheckButton(label="Näytä piilotiedostot"))
        menu_box.append(Gtk.Switch(active=True, halign=Gtk.Align.START))
        popover.set_child(menu_box)
        header.pack_end(menu)
        box.append(header)
        split = Gtk.Box(hexpand=True, vexpand=True)
        box.append(split)
        sidebar = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=4, width_request=170, margin_top=0)
        sidebar.add_css_class("navigation-sidebar")
        style = Gtk.CssProvider()
        style.load_from_data(b".preview-sidebar { background-color: var(--sidebar-bg-color); padding: 12px 8px; } .preview-card { background-color: var(--card-bg-color); padding: 18px; border-radius: 14px; } .preview-view { background-color: var(--view-bg-color); } .preview-footer { font-size: 12px; color: #94a3b1; padding: 12px; }")
        Gtk.StyleContext.add_provider_for_display(Gdk.Display.get_default(), style, Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION)
        sidebar.add_css_class("preview-sidebar")
        for name, icon in (("Koti", "user-home-symbolic"), ("Viimeisimmät", "document-open-recent-symbolic"), ("Asiakirjat", "folder-documents-symbolic"), ("Lataukset", "folder-download-symbolic"), ("Kuvat", "folder-pictures-symbolic"), ("Musiikki", "folder-music-symbolic"), ("Videot", "folder-videos-symbolic"), ("Roskakori", "user-trash-symbolic")):
            button = Gtk.Button()
            button.add_css_class("flat")
            row = Gtk.Box(spacing=10)
            row.append(Gtk.Image.new_from_icon_name(icon))
            row.append(Gtk.Label(label=name, xalign=0))
            button.set_child(row)
            sidebar.append(button)
        split.append(sidebar)
        main = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=18, hexpand=True, margin_top=0)
        main.add_css_class("preview-view")
        split.append(main)
        content = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=20, margin_start=24, margin_end=24, margin_top=24, margin_bottom=24, hexpand=True)
        main.append(content)
        path = Gtk.Label(label="Koti  /  käyttäjä", xalign=0)
        path.add_css_class("heading")
        content.append(path)
        folders = Gtk.FlowBox(selection_mode=Gtk.SelectionMode.NONE, max_children_per_line=3, min_children_per_line=3, column_spacing=12, row_spacing=18)
        for name, icon in (("Asiakirjat", "folder-documents"), ("Lataukset", "folder-download"), ("Kuvat", "folder-pictures"), ("Musiikki", "folder-music"), ("Videot", "folder-videos"), ("Projektit", "folder")):
            item = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=8, margin_start=8, margin_end=8)
            image = Gtk.Image.new_from_icon_name(icon)
            image.set_pixel_size(64)
            item.append(image)
            item.append(Gtk.Label(label=name))
            folders.insert(item, -1)
        content.append(folders)
        content.append(Gtk.Separator())
        label = Gtk.Label(label="Sovellukset", xalign=0)
        label.add_css_class("heading")
        content.append(label)
        apps = Gtk.Box(spacing=20, homogeneous=True)
        for name in ("browser", "terminal", "code", "music", "settings"):
            image = Gtk.Image.new_from_file(str(engine.DATA / "variants" / variant / "icon-preview" / (name + ".svg")))
            image.set_pixel_size(54)
            apps.append(image)
        content.append(apps)
        card = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=16)
        card.add_css_class("preview-card")
        title = Gtk.Label(label=engine.palette(variant)["name"], xalign=0)
        title.add_css_class("title-2")
        card.append(title)
        description = Gtk.Label(label="Mustaa, grafiittia ja hillittyjä tummia sävyjä.", xalign=0, wrap=True)
        card.append(description)
        row = Gtk.Box(spacing=12)
        button = Gtk.Button(label="Ota käyttöön")
        button.add_css_class("suggested-action")
        row.append(button)
        row.append(Gtk.Button(label="Peruuta"))
        row.append(Gtk.Switch(active=True, valign=Gtk.Align.CENTER, halign=Gtk.Align.END, hexpand=True))
        card.append(row)
        content.append(card)
        scale = Gtk.Scale.new_with_range(Gtk.Orientation.HORIZONTAL, 0, 100, 1)
        scale.set_value(64)
        scale.set_draw_value(False)
        content.append(scale)
        box.append(Gtk.Label(label="Esikatselu oikeilla GTK-säätimillä · Ubuntu 26.10 / GNOME 51", css_classes=["preview-footer"]))
        window.present()


sys.exit(App().run([sys.argv[0]]))
